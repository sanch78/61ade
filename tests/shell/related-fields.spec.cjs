const {test,expect}=require('@playwright/test');
test('checkbox grid, descriptive filters and a single main form save related values',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByLabel('Felhasználónév',{exact:true}).fill('synthetic');await page.getByLabel('Jelszó',{exact:true}).fill('synthetic-password');await page.getByRole('button',{name:'Bejelentkezés',exact:true}).click();
 await page.getByRole('menuitem',{name:'Items',exact:true}).click();
 await page.getByRole('button',{name:'Hozzáadás',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await expect(dialog.getByRole('checkbox',{name:'Archived',exact:true})).not.toBeChecked();
 await expect(dialog.getByRole('checkbox',{name:'Notifications',exact:true})).toBeChecked();
 const title='Synthetic '+Date.now();await dialog.getByLabel('Title',{exact:true}).fill(title);
 await dialog.getByRole('button',{name:'Mentés',exact:true}).click();
 await page.getByRole('button',{name:'confirm',exact:true}).click();
 const row=page.getByRole('row').filter({hasText:title});await expect(row).toBeVisible({timeout:10000});
 const archived=row.getByRole('checkbox',{name:'Archived',exact:true});
 const notify=row.getByRole('checkbox',{name:'Notifications',exact:true});
 await expect(archived).not.toBeChecked();await expect(notify).toBeChecked();
 const width=await archived.locator('xpath=ancestor::*[@role="gridcell"]').evaluate(e=>e.getBoundingClientRect().width);expect(width).toBe(100);
 await archived.locator('xpath=..').locator('.dhx_checkbox__visual-input').click();await expect(archived).not.toBeChecked();
 await row.click();await page.getByRole('button',{name:'Módosítás',exact:true}).click();
 await dialog.getByRole('checkbox',{name:'Archived',exact:true}).locator('xpath=ancestor::label').click();
 await dialog.getByRole('checkbox',{name:'Notifications',exact:true}).locator('xpath=ancestor::label').click();
 await dialog.getByRole('button',{name:'Mentés',exact:true}).click();await page.getByRole('button',{name:'confirm',exact:true}).click();
 await expect(archived).toBeChecked({timeout:10000});await expect(notify).not.toBeChecked();
 await page.getByRole('combobox',{name:'Notifications',exact:true}).selectOption({label:'On'});
 await page.getByRole('button',{name:'Szűrés',exact:true}).click();await expect(row).toHaveCount(0);
 await page.getByRole('combobox',{name:'Notifications',exact:true}).selectOption({label:'Off'});
 await page.getByRole('button',{name:'Szűrés',exact:true}).click();await expect(row).toBeVisible();
 await row.click();await page.getByRole('button',{name:'Módosítás',exact:true}).click();
 await expect(dialog.getByRole('checkbox',{name:'Archived',exact:true})).toBeChecked();
 await expect(dialog.getByRole('checkbox',{name:'Notifications',exact:true})).not.toBeChecked();
 expect(errors).toEqual([]);
 await page.screenshot({path:'codex/tmp/related-fields.png',fullPage:true});
});
